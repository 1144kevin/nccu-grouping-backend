begin;
create temporary table safety_fixture(name text,user_id uuid,session_id uuid);
insert into safety_fixture values('安全甲',gen_random_uuid(),gen_random_uuid()),('安全乙',gen_random_uuid(),gen_random_uuid()),('安全丙',gen_random_uuid(),gen_random_uuid());
insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data)
 select user_id,user_id::text||'@example.test',now(),jsonb_build_object('display_name',name) from safety_fixture;
insert into auth.sessions(id,user_id) select session_id,user_id from safety_fixture;
grant select on safety_fixture to authenticated;
set local role authenticated;
do $test$
declare a record; b record; c record; pa jsonb; pb jsonb; j jsonb; value jsonb; input jsonb;
begin
 select * into a from safety_fixture where name='安全甲'; select * into b from safety_fixture where name='安全乙'; select * into c from safety_fixture where name='安全丙';
 input:=jsonb_build_object('content','隔離交易的雲端封鎖功能測試，不會真的下單。','tags',jsonb_build_array('驗證'),'capacity',4,
  'deadline_at',clock_timestamp()+interval '2 hours','price_per_person',null,'location',jsonb_build_object('name','合成測試點','latitude',24.987,'longitude',121.576));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'session_id',a.session_id,'role','authenticated')::text,true);
 pa:=public.core_dispatch('create',jsonb_build_object('request_key','safety-post-alpha','value',input));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b.user_id,'session_id',b.session_id,'role','authenticated')::text,true);
 pb:=public.core_dispatch('create',jsonb_build_object('request_key','safety-post-bravo','value',input));
 perform public.core_dispatch('join',jsonb_build_object('post_id',pa->>'id','expected_version',pa->'version'));
 perform public.core_chat('send',jsonb_build_object('post_id',pb->>'id','content','封鎖後應隱藏的秘密','client_key','safety-chat-bravo'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'session_id',a.session_id,'role','authenticated')::text,true);
 j:=public.core_dispatch('join',jsonb_build_object('post_id',pb->>'id','expected_version',pb->'version'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b.user_id,'session_id',b.session_id,'role','authenticated')::text,true);
 perform public.core_dispatch('decide',jsonb_build_object('join_id',j->>'id','status','accepted'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',c.user_id,'session_id',c.session_id,'role','authenticated')::text,true);
 pb:=public.core_dispatch('post',jsonb_build_object('post_id',pb->>'id'));
 j:=public.core_dispatch('join',jsonb_build_object('post_id',pb->>'id','expected_version',pb->'version'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b.user_id,'session_id',b.session_id,'role','authenticated')::text,true);
 perform public.core_dispatch('decide',jsonb_build_object('join_id',j->>'id','status','accepted'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',c.user_id,'session_id',c.session_id,'role','authenticated')::text,true);
 perform public.core_chat('send',jsonb_build_object('post_id',pb->>'id','content','第三位正常訊息','client_key','safety-chat-charlie'));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'session_id',a.session_id,'role','authenticated')::text,true);
 perform public.core_user_blocks('put',jsonb_build_object('user_id',b.user_id));
 assert jsonb_array_length(public.core_user_blocks('list')->'items')=1;
 perform public.core_user_blocks('put',jsonb_build_object('user_id',b.user_id));
 assert jsonb_array_length(public.core_user_blocks('list')->'items')=1;
 value:=public.core_dispatch('posts',jsonb_build_object('scope','feed'));
 assert not exists(select 1 from jsonb_array_elements(value->'items') p where p->>'author_id'=b.user_id::text);
 assert public.core_dispatch('post',jsonb_build_object('post_id',pb->>'id'))->>'my_status'='accepted';
 value:=public.core_chat('messages',jsonb_build_object('post_id',pb->>'id'));
 assert jsonb_array_length(value->'messages')=1; assert not (value->>'can_send')::boolean;
 assert value->'messages'->0->>'content'='第三位正常訊息';
 value:=public.core_search(jsonb_build_object('scope','messages','q','秘密'));
 assert jsonb_array_length(value->'items')=0;
 value:=public.core_chat_activity('status');
 assert (value->>'total_unread')::integer=1;
 begin perform public.core_public_user('profile',jsonb_build_object('user_id',b.user_id)); raise exception 'blocked profile exposed';
 exception when sqlstate 'PT404' then null; end;
 begin perform public.core_chat('send',jsonb_build_object('post_id',pb->>'id','content','不應送出','client_key','safety-chat-blocked')); raise exception 'blocked message sent';
 exception when sqlstate 'PT403' then null; end;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b.user_id,'session_id',b.session_id,'role','authenticated')::text,true);
 assert jsonb_array_length(public.core_user_blocks('list')->'items')=0;
 begin perform public.core_dispatch('post',jsonb_build_object('post_id',pa->>'id')); raise exception 'reverse blocked post exposed';
 exception when sqlstate 'PT404' then null; end;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'session_id',a.session_id,'role','authenticated')::text,true);
 perform public.core_user_blocks('remove',jsonb_build_object('user_id',b.user_id));
 assert jsonb_array_length(public.core_user_blocks('list')->'items')=0;
 value:=public.core_chat('messages',jsonb_build_object('post_id',pb->>'id'));
 assert (value->>'can_send')::boolean and jsonb_array_length(value->'messages')=2;
 assert not has_function_privilege('authenticated','core_private.dispatch(text,jsonb)','EXECUTE');
 assert not has_table_privilege('authenticated','public.core_user_blocks','SELECT');
 assert not has_function_privilege('anon','public.core_user_blocks(text,jsonb)','EXECUTE');
end $test$;
reset role;
rollback;
